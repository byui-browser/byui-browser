#[test]
fn break_all_wraps_long_words_but_nowrap_disables_it() {
    for (mode, lines) in [("normal", 1), ("break-all", 3), ("break-word", 3)] {
        let (doc, tree) = lay_out(
            "<div id='a'>abcdef</div>",
            &format!("#a {{ width:16px; word-break:{mode} }}"),
            200.0,
        );
        let b = find(&tree.root, id(&doc, "a")).unwrap();
        assert_eq!(b.lines.len(), lines, "{mode}");
        assert!(
            paint::paint_document(&tree)
                .items
                .iter()
                .any(|item| matches!(item, paint::DisplayItem::Text { .. }))
        );
    }
    let (doc, tree) = lay_out(
        "<div id='a'>abcdef</div>",
        "#a { width:16px; word-break:break-all; white-space:nowrap }",
        200.0,
    );
    assert_eq!(find(&tree.root, id(&doc, "a")).unwrap().lines.len(), 1);
}

#[test]
fn keep_all_prevents_cjk_breaks_and_break_all_keeps_graphemes() {
    for (mode, count) in [("normal", 3), ("keep-all", 1)] {
        let (doc, tree) = lay_out(
            "<div id='a'>中文文</div>",
            &format!("#a {{ width:8px; word-break:{mode} }}"),
            200.0,
        );
        assert_eq!(find(&tree.root, id(&doc, "a")).unwrap().lines.len(), count);
    }
    let (_, tree) = lay_out(
        "<div>áb</div>",
        "div { width:8px; word-break:break-all }",
        200.0,
    );
    let texts: Vec<_> = tree
        .paint_order()
        .into_iter()
        .filter_map(|item| match item {
            PaintItem::Text(t) => Some(t.text.as_str()),
            _ => None,
        })
        .collect();
    assert_eq!(texts, ["á", "b"]);
}

#[test]
fn logical_padding_honors_direction_priority_and_source_order() {
    for (rule, left, right) in [
        ("padding-inline-end:20px", 0.0, 20.0),
        ("direction:rtl; padding-inline-end:20px", 20.0, 0.0),
        ("padding-inline-end:20px; padding-right:5px", 0.0, 5.0),
        ("padding-right:5px; padding-inline-end:20px", 0.0, 20.0),
        (
            "padding-inline-end:20px!important; padding-right:5px",
            0.0,
            20.0,
        ),
    ] {
        let (doc, tree) = lay_out("<div id='a'>text</div>", &format!("#a {{{rule}}}"), 200.0);
        let b = find(&tree.root, id(&doc, "a")).unwrap();
        assert_eq!((b.padding.left, b.padding.right), (left, right), "{rule}");
    }
}

#[test]
fn maximum_block_size_caps_height_but_minimum_wins() {
    for (rule, expected) in [
        ("max-block-size:30px", 30.0),
        ("max-block-size:30px; min-height:50px", 50.0),
        ("max-block-size:30px; max-height:40px", 40.0),
        ("max-height:40px; max-block-size:30px", 30.0),
    ] {
        let (doc, tree) = lay_out(
            "<div id='a'>text</div>",
            &format!("#a {{height:100px; {rule}}}"),
            200.0,
        );
        assert_eq!(
            find(&tree.root, id(&doc, "a")).unwrap().rect.height,
            expected,
            "{rule}"
        );
    }
}

#[test]
fn outline_offset_changes_paint_without_changing_layout() {
    for offset in [-3.0, 0.0, 5.0] {
        let (doc, tree) = lay_out(
            "<div id='a'></div>",
            &format!(
                "body {{margin:10px}} #a {{width:40px;height:20px;outline:2px solid red;outline-offset:{offset}px}}"
            ),
            200.0,
        );
        let b = find(&tree.root, id(&doc, "a")).unwrap();
        assert_eq!((b.rect.width, b.rect.height), (40.0, 20.0));
        assert_eq!(b.style.outline_offset, offset);
        let list = paint::paint_document(&tree);
        assert!(list.items.iter().any(|item| matches!(item, paint::DisplayItem::FillRect { rect, color } if color.r == 255 && color.g == 0 && (rect.x - (b.rect.x - 2.0 - offset)).abs() < 0.01)));
    }
}

#[test]
fn cursor_and_selection_and_rendering_hints_reach_fragments() {
    let (doc, tree) = lay_out(
        "<div id='a'>hello</div>",
        "#a {cursor:url(a.cur), crosshair; -webkit-user-select:none; text-rendering:optimizeSpeed}",
        200.0,
    );
    let t = tree
        .paint_order()
        .into_iter()
        .find_map(|item| match item {
            PaintItem::Text(t) => Some(t),
            _ => None,
        })
        .unwrap();
    assert_eq!(tree.cursor_at(t.rect.x + 1.0, t.rect.y + 1.0), "crosshair");
    assert_eq!(t.user_select, "none");
    assert_eq!(
        find(&tree.root, id(&doc, "a")).unwrap().style.cursor,
        "crosshair"
    );
    assert!(
        paint::paint_document(&tree)
            .items
            .iter()
            .any(|item| matches!(
                item,
                paint::DisplayItem::Text {
                    snap_glyphs: true,
                    ..
                }
            ))
    );
}

