//! End-to-end layout tests: HTML and CSS in, fragment geometry out.
//!
//! The test font is fixed-pitch so expected values can be checked by hand:
//! at 16px every character advances 8px, the ascent is 12.8px, the descent
//! 3.2px, and `line-height: normal` is 19.2px (baseline 14.4px below the
//! line top).

use html::{HTMLDocument, NodeID};

use layout::{
    FontMetrics, LayoutBox, LayoutTree, LineFragment, PaintItem, Size, VerticalMetrics,
    layout_document,
};

struct TestFont;

impl FontMetrics for TestFont {
    fn advance(&self, _character: char, font_size: f32) -> f32 {
        font_size / 2.0
    }

    fn vertical_metrics(&self, font_size: f32) -> VerticalMetrics {
        VerticalMetrics {
            ascent: font_size * 0.8,
            descent: font_size * 0.2,
            line_gap: font_size * 0.2,
        }
    }
}

fn lay_out(html: &str, css: &str, width: f32) -> (HTMLDocument, LayoutTree) {
    let document = html::parse_raw_html(format!("<html><body>{html}</body></html>"));
    let styles = css::style_document(&document, &[css::parse_stylesheet(css)]);
    let tree = layout_document(
        &document,
        &styles,
        Size {
            width,
            height: 600.0,
        },
        &TestFont,
    );
    (document, tree)
}

fn id(document: &HTMLDocument, id: &str) -> NodeID {
    document.get_element_by_id(id).expect("element with id")
}

/// Finds the box generated by `node`, looking inside line boxes for atomics.
fn find(layout_box: &LayoutBox, node: NodeID) -> Option<&LayoutBox> {
    if layout_box.node == Some(node) {
        return Some(layout_box);
    }
    let atomics = layout_box
        .lines
        .iter()
        .flat_map(|line| &line.fragments)
        .filter_map(|fragment| match fragment {
            LineFragment::Atomic(atomic) => Some(atomic),
            _ => None,
        });
    layout_box
        .children
        .iter()
        .chain(atomics)
        .find_map(|child| find(child, node))
}

#[test]
fn minimum_dimensions_expand_blocks_and_painted_backgrounds() {
    let (doc, tree) = lay_out(
        "<div id='a'></div>",
        "body { margin:0 } #a { width:10px; height:5px; min-width:80px; min-height:60px; background-color:red }",
        200.0,
    );
    let b = find(&tree.root, id(&doc, "a")).unwrap();
    assert_eq!((b.rect.width, b.rect.height), (80.0, 60.0));
    let list = paint::paint_document(&tree);
    assert!(list.items.iter().any(|item| matches!(item, paint::DisplayItem::FillRect { rect, color } if rect.width == 80.0 && rect.height == 60.0 && color.r == 255 && color.g == 0)));
}

#[test]
fn hidden_content_keeps_space_and_visible_descendants_paint() {
    let (doc, tree) = lay_out(
        "<div id='a'>secret<span style='visibility:visible'>shown</span></div><div id='b'>after</div>",
        "body { margin:0 } #a { visibility:hidden; height:40px; background-color:red }",
        200.0,
    );
    assert_eq!(find(&tree.root, id(&doc, "b")).unwrap().rect.y, 40.0);
    let painted = format!("{:?}", paint::paint_document(&tree));
    assert!(!painted.contains("secret"));
    assert!(painted.contains("shown"));
}

#[test]
fn text_overflow_ellipsis_reaches_paint_with_a_clip() {
    let (_, tree) = lay_out(
        "<div>abcdefghijk</div>",
        "body { margin:0 } div { width:40px; overflow:hidden; white-space:nowrap; text-overflow:ellipsis }",
        200.0,
    );
    let texts: Vec<_> = tree
        .paint_order()
        .into_iter()
        .filter_map(|item| match item {
            PaintItem::Text(t) => Some(t),
            _ => None,
        })
        .collect();
    assert_eq!(texts.len(), 1);
    assert_eq!(texts[0].text, "abcd…");
    assert_eq!(texts[0].clip.unwrap().width, 40.0);
    assert!(format!("{:?}", paint::paint_document(&tree)).contains("abcd…"));
}

#[test]
fn animated_minimum_height_changes_layout_and_paint() {
    let doc = html::parse_raw_html("<html><body><div id='a'></div></body></html>".to_owned());
    let sheets = [css::parse_stylesheet(
        "body { margin:0 } @keyframes grow { from { min-height:20px } to { min-height:100px } } #a { background-color:red; animation:grow 2s linear forwards }",
    )];
    let styles = css::style_document_with_state_at(
        &doc,
        &sheets,
        Default::default(),
        std::time::Duration::from_secs(1),
    );
    let tree = layout_document(
        &doc,
        &styles,
        Size {
            width: 200.0,
            height: 600.0,
        },
        &TestFont,
    );
    assert_eq!(find(&tree.root, id(&doc, "a")).unwrap().rect.height, 60.0);
    assert!(paint::paint_document(&tree).items.iter().any(|item| matches!(item, paint::DisplayItem::FillRect { rect, color } if rect.height == 60.0 && color.r == 255 && color.g == 0)));
}

