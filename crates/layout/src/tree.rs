//! The fragment tree: layout's output.
//!
//! All coordinates are absolute CSS pixels with the origin at the top-left of
//! the initial containing block (the viewport).

use css::CssColor;
use html::NodeID;

use crate::{Edges, Rect};

/// Paint-relevant computed values for a box or inline box fragment.
///
/// Only colors are painted today; borders and other decorations are not
/// supported yet.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct BoxStyle {
    /// The background color, or `None` when it is transparent or unsupported.
    pub background_color: Option<CssColor>,
    /// The computed `color`, used for text.
    pub text_color: CssColor,
}

impl Default for BoxStyle {
    fn default() -> Self {
        Self {
            background_color: None,
            text_color: css::user_agent_default_color("color")
                .expect("user-agent stylesheet must define html color"),
        }
    }
}

/// What kind of box a [`LayoutBox`] is.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum BoxKind {
    /// The initial containing block. Its rect is the viewport and its
    /// background is the canvas background.
    Viewport,
    /// A block-level box generated by an element.
    Block,
    /// An anonymous block box wrapping inline content that sits next to
    /// block-level siblings (CSS 2.2 §9.2.1.1). Its `node` is `None`.
    AnonymousBlock,
    /// An atomic inline-level box such as `display: inline-block`. It appears
    /// inside a [`LineBox`] as [`LineFragment::Atomic`].
    InlineBlock,
}

/// A box fragment: a block container laid out with the CSS box model.
#[derive(Debug, Clone, PartialEq)]
pub struct LayoutBox {
    /// The kind of box.
    pub kind: BoxKind,
    /// The element that generated the box; `None` for the viewport and for
    /// anonymous boxes.
    pub node: Option<NodeID>,
    /// The border box in absolute CSS pixels.
    pub rect: Rect,
    /// Used margin widths. Vertical margins are the box's own margins before
    /// collapsing.
    pub margin: Edges,
    /// Used padding widths. Borders are not supported yet, so the border box
    /// and the padding box coincide.
    pub padding: Edges,
    /// Paint-relevant computed values.
    pub style: BoxStyle,
    /// Block-level child boxes, in tree order. Empty when the box contains
    /// inline content.
    pub children: Vec<LayoutBox>,
    /// Line boxes when the box establishes an inline formatting context, in
    /// order from top to bottom.
    pub lines: Vec<LineBox>,
}

impl LayoutBox {
    /// The content box: the border box minus the padding.
    pub fn content_rect(&self) -> Rect {
        Rect {
            x: self.rect.x + self.padding.left,
            y: self.rect.y + self.padding.top,
            width: self.rect.width - self.padding.horizontal(),
            height: self.rect.height - self.padding.vertical(),
        }
    }

    pub(crate) fn translate(&mut self, dx: f32, dy: f32) {
        self.rect = self.rect.translate(dx, dy);
        for child in &mut self.children {
            child.translate(dx, dy);
        }
        for line in &mut self.lines {
            line.translate(dx, dy);
        }
    }
}

/// One line box of an inline formatting context (CSS 2.2 §9.4.2).
#[derive(Debug, Clone, PartialEq)]
pub struct LineBox {
    /// The line box: as wide as the containing block's content box and as
    /// tall as its inline content (CSS 2.2 §10.8).
    pub rect: Rect,
    /// The y coordinate of the line's alphabetic baseline.
    pub baseline: f32,
    /// The line's content in tree order, which is also paint order.
    pub fragments: Vec<LineFragment>,
}

impl LineBox {
    pub(crate) fn translate(&mut self, dx: f32, dy: f32) {
        self.rect = self.rect.translate(dx, dy);
        self.baseline += dy;
        for fragment in &mut self.fragments {
            match fragment {
                LineFragment::InlineBox(inline) => inline.rect = inline.rect.translate(dx, dy),
                LineFragment::Text(text) => {
                    text.rect = text.rect.translate(dx, dy);
                    text.baseline += dy;
                }
                LineFragment::Atomic(atomic) => atomic.translate(dx, dy),
            }
        }
    }
}

/// An item placed in a line box.
#[derive(Debug, Clone, PartialEq)]
pub enum LineFragment {
    /// The part of an inline box (for example a `<span>`) on this line. Its
    /// content follows it in the fragment list.
    InlineBox(InlineBoxFragment),
    /// A run of text.
    Text(TextFragment),
    /// An atomic inline such as an inline-block.
    Atomic(LayoutBox),
}

/// The part of a non-replaced inline box that lies on one line.
#[derive(Debug, Clone, PartialEq)]
pub struct InlineBoxFragment {
    /// The element that generated the inline box.
    pub node: NodeID,
    /// The fragment's border box. Its height is the font's content area plus
    /// vertical padding, which does not affect the line height
    /// (CSS 2.2 §10.6.1). Horizontal padding is included only on the sides
    /// where this fragment holds the inline box's start or end edge.
    pub rect: Rect,
    /// Paint-relevant computed values.
    pub style: BoxStyle,
}

/// A run of text placed on a line.
#[derive(Debug, Clone, PartialEq)]
pub struct TextFragment {
    /// The DOM text node the run comes from.
    pub node: NodeID,
    /// The text node's parent element, which is the hit-test target for the
    /// text.
    pub element: Option<NodeID>,
    /// The run's content area: its advance width by the font's ascent plus
    /// descent.
    pub rect: Rect,
    /// The y coordinate of the alphabetic baseline the glyphs sit on.
    pub baseline: f32,
    /// The text after white-space processing.
    pub text: String,
    /// The computed font size in CSS pixels.
    pub font_size: f32,
    /// The text color.
    pub color: CssColor,
}

/// The complete layout output for one document and viewport.
#[derive(Debug, Clone, PartialEq)]
pub struct LayoutTree {
    /// The initial containing block. Its `style.background_color` is the
    /// canvas background propagated from the root element or `body`
    /// (CSS Backgrounds 3 §2.11.2); `None` means the user agent's default
    /// canvas color.
    pub root: LayoutBox,
}

/// One step of painting, in the order CSS 2.2 Appendix E prescribes.
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum PaintItem<'a> {
    /// The background of a block-level box or atomic inline. For
    /// [`BoxKind::Viewport`] this is the canvas background.
    BoxDecorations(&'a LayoutBox),
    /// The background of an inline box fragment.
    InlineBox(&'a InlineBoxFragment),
    /// A text run.
    Text(&'a TextFragment),
}

impl LayoutTree {
    /// Lists everything to paint, back to front.
    ///
    /// Within the root stacking context this follows CSS 2.2 Appendix E: the
    /// canvas, then the backgrounds of all block-level boxes in
    /// tree order, then the inline content of every line box in tree order.
    /// Atomic inlines are painted as if they created a stacking context, at
    /// their place in the line. Positioned boxes, floats, and `z-index` are
    /// not supported yet, so there are no other layers.
    pub fn paint_order(&self) -> Vec<PaintItem<'_>> {
        let mut items = Vec::new();
        paint_atomically(&self.root, &mut items);
        items
    }

    /// Returns the element under a CSS-pixel point, or `None` when the point
    /// hits only the canvas.
    ///
    /// The topmost painted item wins, so this matches what is drawn: text hits
    /// its parent element, inline box fragments hit their element, and block
    /// boxes hit their element anywhere in their border box. Anonymous boxes
    /// are transparent to hit testing. Content overflowing its parent is still
    /// hit, since overflow clipping is not implemented.
    pub fn hit_test(&self, x: f32, y: f32) -> Option<NodeID> {
        self.paint_order()
            .into_iter()
            .rev()
            .find_map(|item| match item {
                PaintItem::BoxDecorations(layout_box) => {
                    layout_box.node.filter(|_| layout_box.rect.contains(x, y))
                }
                PaintItem::InlineBox(inline) => inline.rect.contains(x, y).then_some(inline.node),
                PaintItem::Text(text) => text.element.filter(|_| text.rect.contains(x, y)),
            })
    }
}

fn paint_atomically<'a>(layout_box: &'a LayoutBox, items: &mut Vec<PaintItem<'a>>) {
    items.push(PaintItem::BoxDecorations(layout_box));
    for child in &layout_box.children {
        push_block_decorations(child, items);
    }
    push_inline_content(layout_box, items);
}

fn push_block_decorations<'a>(layout_box: &'a LayoutBox, items: &mut Vec<PaintItem<'a>>) {
    items.push(PaintItem::BoxDecorations(layout_box));
    for child in &layout_box.children {
        push_block_decorations(child, items);
    }
}

fn push_inline_content<'a>(layout_box: &'a LayoutBox, items: &mut Vec<PaintItem<'a>>) {
    for line in &layout_box.lines {
        for fragment in &line.fragments {
            match fragment {
                LineFragment::InlineBox(inline) => items.push(PaintItem::InlineBox(inline)),
                LineFragment::Text(text) => items.push(PaintItem::Text(text)),
                LineFragment::Atomic(atomic) => paint_atomically(atomic, items),
            }
        }
    }
    for child in &layout_box.children {
        push_inline_content(child, items);
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn block(node: Option<usize>, rect: Rect, children: Vec<LayoutBox>) -> LayoutBox {
        LayoutBox {
            kind: if node.is_some() {
                BoxKind::Block
            } else {
                BoxKind::Viewport
            },
            node: node.map(NodeID::new),
            rect,
            margin: Edges::default(),
            padding: Edges::default(),
            style: BoxStyle::default(),
            children,
            lines: Vec::new(),
        }
    }

    fn rect(x: f32, y: f32, size: f32) -> Rect {
        Rect {
            x,
            y,
            width: size,
            height: size,
        }
    }

    #[test]
    fn hit_test_returns_the_topmost_box_under_the_point() {
        let tree = LayoutTree {
            root: block(
                None,
                rect(0.0, 0.0, 100.0),
                vec![block(
                    Some(1),
                    rect(0.0, 0.0, 10.0),
                    vec![block(Some(2), rect(5.0, 5.0, 10.0), Vec::new())],
                )],
            ),
        };

        assert_eq!(tree.hit_test(7.0, 7.0), Some(NodeID::new(2)));
        assert_eq!(tree.hit_test(1.0, 1.0), Some(NodeID::new(1)));
        assert_eq!(tree.hit_test(12.0, 12.0), Some(NodeID::new(2)));
        assert_eq!(tree.hit_test(40.0, 40.0), None);
    }

    #[test]
    fn inline_content_paints_after_all_block_backgrounds() {
        let mut parent = block(Some(1), rect(0.0, 0.0, 10.0), Vec::new());
        parent.lines.push(LineBox {
            rect: rect(0.0, 0.0, 10.0),
            baseline: 8.0,
            fragments: vec![LineFragment::Text(TextFragment {
                node: NodeID::new(3),
                element: Some(NodeID::new(1)),
                rect: rect(0.0, 0.0, 10.0),
                baseline: 8.0,
                text: "a".into(),
                font_size: 10.0,
                color: BoxStyle::default().text_color,
            })],
        });
        let sibling = block(Some(2), rect(0.0, 10.0, 10.0), Vec::new());
        let tree = LayoutTree {
            root: block(None, rect(0.0, 0.0, 100.0), vec![parent, sibling]),
        };
        let order = tree
            .paint_order()
            .into_iter()
            .map(|item| match item {
                PaintItem::BoxDecorations(layout_box) => {
                    format!("box {:?}", layout_box.node.map(|node| node.get()))
                }
                PaintItem::InlineBox(_) => "inline".to_owned(),
                PaintItem::Text(text) => format!("text {}", text.text),
            })
            .collect::<Vec<_>>();
        assert_eq!(order, ["box None", "box Some(1)", "box Some(2)", "text a"]);
    }
}
