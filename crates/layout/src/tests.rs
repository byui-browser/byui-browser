//! End-to-end layout tests: HTML and CSS in, fragment geometry out.
//!
//! The test font is fixed-pitch so expected values can be checked by hand:
//! at 16px every character advances 8px, the ascent is 12.8px, the descent
//! 3.2px, and `line-height: normal` is 19.2px (baseline 14.4px below the
//! line top).

use html::{HTMLDocument, NodeID};

use crate::{
    BoxKind, FontMetrics, LayoutBox, LayoutTree, LineFragment, PaintItem, Size, VerticalMetrics,
    layout_document,
};

struct TestFont;

impl FontMetrics for TestFont {
    fn advance(&self, _character: char, font_size: f32) -> f32 {
        font_size / 2.0
    }

    fn vertical_metrics(&self, font_size: f32) -> VerticalMetrics {
        VerticalMetrics {
            ascent: font_size * 0.8,
            descent: font_size * 0.2,
            line_gap: font_size * 0.2,
        }
    }
}

const LINE: f32 = 19.2;

fn lay_out(html: &str, css: &str, width: f32) -> (HTMLDocument, LayoutTree) {
    let document = html::parse_raw_html(html.to_owned());
    let styles = css::style_document(&document, &[css::parse_stylesheet(css)]);
    let tree = layout_document(
        &document,
        &styles,
        Size {
            width,
            height: 600.0,
        },
        &TestFont,
    );
    (document, tree)
}

fn id(document: &HTMLDocument, id: &str) -> NodeID {
    document.get_element_by_id(id).expect("element with id")
}

/// Finds the box generated by `node`, looking inside line boxes for atomics.
fn find(layout_box: &LayoutBox, node: NodeID) -> Option<&LayoutBox> {
    if layout_box.node == Some(node) {
        return Some(layout_box);
    }
    let atomics = layout_box
        .lines
        .iter()
        .flat_map(|line| &line.fragments)
        .filter_map(|fragment| match fragment {
            LineFragment::Atomic(atomic) => Some(atomic),
            _ => None,
        });
    layout_box
        .children
        .iter()
        .chain(atomics)
        .find_map(|child| find(child, node))
}

fn box_for<'a>(tree: &'a LayoutTree, document: &HTMLDocument, name: &str) -> &'a LayoutBox {
    find(&tree.root, id(document, name)).expect("element has a box")
}

fn texts(layout_box: &LayoutBox) -> Vec<String> {
    layout_box
        .lines
        .iter()
        .map(|line| {
            line.fragments
                .iter()
                .filter_map(|fragment| match fragment {
                    LineFragment::Text(text) => Some(text.text.as_str()),
                    _ => None,
                })
                .collect()
        })
        .collect()
}

fn assert_close(actual: f32, expected: f32) {
    assert!(
        (actual - expected).abs() < 0.01,
        "expected {expected}, got {actual}"
    );
}

#[test]
fn body_margin_offsets_blocks_that_fill_the_containing_block_width() {
    let (document, tree) = lay_out(
        "<html id='root'><body id='body'><div id='a'>x</div></body></html>",
        "",
        800.0,
    );
    let root = box_for(&tree, &document, "root");
    let body = box_for(&tree, &document, "body");
    let div = box_for(&tree, &document, "a");
    assert_eq!(
        (root.rect.x, root.rect.y, root.rect.width),
        (0.0, 0.0, 800.0)
    );
    assert_eq!(
        (body.rect.x, body.rect.y, body.rect.width),
        (8.0, 8.0, 784.0)
    );
    assert_eq!((div.rect.x, div.rect.y, div.rect.width), (8.0, 8.0, 784.0));
    assert_close(div.rect.height, LINE);
    // The root establishes a formatting context, so body's margins stay
    // inside it.
    assert_close(root.rect.height, 8.0 + LINE + 8.0);
}

#[test]
fn parent_and_first_child_margins_collapse() {
    let (document, tree) = lay_out(
        "<html id='root'><body id='body'><h1 id='h'>T</h1></body></html>",
        "",
        800.0,
    );
    // h1's 0.67em margin (21.44px at 32px) collapses with body's 8px margin.
    let body = box_for(&tree, &document, "body");
    let heading = box_for(&tree, &document, "h");
    assert_close(body.rect.y, 21.44);
    assert_close(heading.rect.y, 21.44);
    assert_close(heading.rect.height, 32.0 * 1.2);
    let root = box_for(&tree, &document, "root");
    assert_close(root.rect.height, 21.44 + 38.4 + 21.44);
}

#[test]
fn adjacent_sibling_margins_collapse_to_the_largest_plus_most_negative() {
    let (document, tree) = lay_out(
        "<body><div id='a'></div><div id='b'></div><div id='c'></div></body>",
        "body { margin: 0 } div { height: 10px }
         #a { margin-bottom: 30px } #b { margin-top: 20px; margin-bottom: 30px }
         #c { margin-top: -10px }",
        800.0,
    );
    let a = box_for(&tree, &document, "a");
    let b = box_for(&tree, &document, "b");
    let c = box_for(&tree, &document, "c");
    assert_eq!(b.rect.y, a.rect.bottom() + 30.0);
    assert_eq!(c.rect.y, b.rect.bottom() + 20.0);
}

#[test]
fn margins_collapse_through_empty_blocks() {
    let (document, tree) = lay_out(
        "<body><div id='a'></div><div id='empty'></div><div id='b'></div></body>",
        "body { margin: 0 } #a, #b { height: 5px } #a { margin-bottom: 10px }
         #empty { margin: 20px 0 }",
        800.0,
    );
    let empty = box_for(&tree, &document, "empty");
    let b = box_for(&tree, &document, "b");
    assert_eq!(empty.rect.height, 0.0);
    assert_eq!(b.rect.y, 5.0 + 20.0);
}

#[test]
fn auto_margins_center_and_over_constraint_ignores_margin_right() {
    let (document, tree) = lay_out(
        "<body><div id='centered'></div><div id='wide'></div></body>",
        "body { margin: 0 } #centered { width: 200px; margin: 0 auto }
         #wide { width: 900px; margin-left: 10px; margin-right: auto }",
        800.0,
    );
    let centered = box_for(&tree, &document, "centered");
    assert_eq!((centered.rect.x, centered.rect.width), (300.0, 200.0));
    assert_eq!(
        (centered.margin.left, centered.margin.right),
        (300.0, 300.0)
    );
    let wide = box_for(&tree, &document, "wide");
    assert_eq!((wide.rect.x, wide.margin.right), (10.0, -110.0));
}

#[test]
fn percentages_resolve_against_the_containing_block() {
    let (document, tree) = lay_out(
        "<html id='root'><body><div id='d'><p id='p'>x</p></div></body></html>",
        "html { height: 50% } body { margin: 0 }
         #d { width: 50%; padding-left: 10% } #p { height: 50%; margin: 0 }",
        800.0,
    );
    // The root's containing block is the viewport, which has a definite
    // height.
    assert_eq!(box_for(&tree, &document, "root").rect.height, 300.0);
    let div = box_for(&tree, &document, "d");
    assert_eq!((div.padding.left, div.rect.width), (80.0, 480.0));
    // The div's height is auto, so a percentage height on its child behaves
    // as auto (CSS 2.2 §10.5).
    assert_close(box_for(&tree, &document, "p").rect.height, LINE);
}

#[test]
fn explicit_height_and_padding_size_the_border_box() {
    let (document, tree) = lay_out(
        "<body><div id='d'><p id='p'>x</p></div></body>",
        "body { margin: 0 } #d { height: 50px; padding: 10px } p { margin: 0 }",
        800.0,
    );
    let div = box_for(&tree, &document, "d");
    assert_eq!((div.rect.width, div.rect.height), (800.0, 70.0));
    let paragraph = box_for(&tree, &document, "p");
    assert_eq!((paragraph.rect.x, paragraph.rect.y), (10.0, 10.0));
    assert_eq!(div.content_rect().width, 780.0);
}

#[test]
fn display_none_and_metadata_generate_no_boxes() {
    let (document, tree) = lay_out(
        "<html><head><title>Title</title></head><body id='body'><div style='display: none'>x</div><p id='p'>y</p><script>z</script></body></html>",
        "",
        800.0,
    );
    let body = box_for(&tree, &document, "body");
    assert_eq!(body.children.len(), 1);
    assert_eq!(body.children[0].node, Some(id(&document, "p")));
    let painted_text = tree
        .paint_order()
        .into_iter()
        .filter_map(|item| match item {
            PaintItem::Text(text) if !text.text.trim().is_empty() => Some(text.text.clone()),
            _ => None,
        })
        .collect::<Vec<_>>();
    assert_eq!(painted_text, ["y"]);
}

