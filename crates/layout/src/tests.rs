#[test]
fn a_block_inside_an_inline_splits_the_inline() {
    let (document, tree) = lay_out(
        "<body><div id='d'><span id='s'>a<p>b</p>c</span></div></body>",
        "",
        800.0,
    );
    let span = id(&document, "s");
    let div = box_for(&tree, &document, "d");
    assert_eq!(div.children.len(), 3);
    for anonymous in [&div.children[0], &div.children[2]] {
        assert!(anonymous.lines[0].fragments.iter().any(
            |fragment| matches!(fragment, LineFragment::InlineBox(inline) if inline.node == span)
        ));
    }
}

