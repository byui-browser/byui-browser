#[test]
fn text_wraps_at_spaces_and_trailing_spaces_are_removed() {
    let (document, tree) = lay_out(
        "<body><p id='p'>aaaa bbbb cccc</p></body>",
        "body { margin: 0 }",
        100.0,
    );
    let paragraph = box_for(&tree, &document, "p");
    assert_eq!(texts(paragraph), ["aaaa bbbb", "cccc"]);
    assert_close(paragraph.lines[1].rect.y - paragraph.lines[0].rect.y, LINE);
    assert_close(
        paragraph.lines[0].baseline - paragraph.lines[0].rect.y,
        14.4,
    );
}

