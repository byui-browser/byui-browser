#[test]
fn the_canvas_takes_the_body_background_when_the_root_has_none() {
    let (document, tree) = lay_out(
        "<html id='root'><body id='body'>x</body></html>",
        "body { background-color: red }",
        800.0,
    );
    assert_eq!(tree.root.style.background_color, css::parse_color("red"));
    assert_eq!(
        box_for(&tree, &document, "body").style.background_color,
        None
    );

    let (document, tree) = lay_out(
        "<html id='root'><body id='body'>x</body></html>",
        "html { background-color: blue } body { background-color: red }",
        800.0,
    );
    assert_eq!(tree.root.style.background_color, css::parse_color("blue"));
    assert_eq!(
        box_for(&tree, &document, "root").style.background_color,
        None
    );
    assert_eq!(
        box_for(&tree, &document, "body").style.background_color,
        css::parse_color("red")
    );
}

#[test]
fn hit_testing_targets_what_is_painted_on_top() {
    let (document, tree) = lay_out(
        "<body id='body'><p id='p'>aa <span id='s'>bb</span></p></body>",
        "",
        800.0,
    );
    let span_text = tree
        .paint_order()
        .into_iter()
        .find_map(|item| match item {
            PaintItem::Text(text) if text.text == "bb" => Some(text.rect),
            _ => None,
        })
        .expect("span text is painted");
    let (x, y) = (span_text.x + 1.0, span_text.y + 1.0);
    assert_eq!(tree.hit_test(x, y), Some(id(&document, "s")));
    let paragraph = box_for(&tree, &document, "p");
    assert_eq!(
        tree.hit_test(paragraph.rect.right() - 1.0, paragraph.rect.y + 1.0),
        Some(id(&document, "p"))
    );
    // Body is the root element here; its 8px margin shows only the canvas.
    assert_eq!(tree.hit_test(1.0, 1.0), None);
}
