#[test]
fn inline_box_padding_takes_inline_space_but_not_line_height() {
    let (document, tree) = lay_out(
        "<body><p id='p'>a<span id='s' style='padding: 10px 4px'>b</span>c</p></body>",
        "body { margin: 0 } p { margin: 0 }",
        800.0,
    );
    let paragraph = box_for(&tree, &document, "p");
    let fragments = &paragraph.lines[0].fragments;
    let LineFragment::InlineBox(span) = &fragments[1] else {
        panic!("expected the span's inline box fragment");
    };
    assert_eq!((span.rect.x, span.rect.width), (8.0, 4.0 + 8.0 + 4.0));
    assert_close(span.rect.height, 16.0 + 20.0);
    let LineFragment::Text(after) = &fragments[3] else {
        panic!("expected text after the span");
    };
    assert_eq!(after.rect.x, 24.0);
    assert_close(paragraph.rect.height, LINE);
}

#[test]
fn inline_blocks_shrink_to_fit_and_align_their_last_baseline() {
    let html = "<body><p id='p'>x<span id='ib' style='display: inline-block; padding: 0 4px'>hi there</span></p></body>";
    let css = "body { margin: 0 } p { margin: 0 }";
    let (document, tree) = lay_out(html, css, 800.0);
    let inline_block = box_for(&tree, &document, "ib");
    assert_eq!(inline_block.kind, BoxKind::InlineBlock);
    assert_eq!(inline_block.rect.width, 8.0 * 8.0 + 8.0);
    let paragraph = box_for(&tree, &document, "p");
    assert_close(inline_block.lines[0].baseline, paragraph.lines[0].baseline);

    // With 40px available the width is clamped up to the min-content width,
    // the longest word.
    let (document, tree) = lay_out(html, css, 40.0);
    let inline_block = box_for(&tree, &document, "ib");
    assert_eq!(inline_block.content_rect().width, 5.0 * 8.0);
    assert_eq!(texts(inline_block), ["hi", "there"]);
}

