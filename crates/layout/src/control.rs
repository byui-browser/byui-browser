//! Default sizes of form controls (HTML §15.5).
//!
//! `<input>`, `<textarea>`, `<select>` and `<button>` stay ordinary block
//! containers so they can hold text, but when the author leaves `width` or
//! `height` as `auto` they take a natural content size measured from the
//! control's own font, the way browsers size them.
//!
//! Partial support: the sizes ignore scrollbars (`<textarea>`), list-box
//! `<select>` elements are sized like drop-downs but `size` lines tall, and
//! checkbox, radio, `image`, `range`, `color` and `file` inputs get no
//! natural size.

use html::{HTMLDocument, NodeID, NodeKind};

use crate::box_tree::BlockBox;
use crate::layout::Context;
use crate::style::Dimension;

/// Room reserved beside a `<select>`'s widest option for its drop-down
/// arrow, in CSS pixels.
const SELECT_ARROW_ROOM: f32 = 20.0;

/// A form control whose `auto` size comes from its font.
#[derive(Debug, Clone, PartialEq)]
pub(crate) enum FormControl {
    /// A single-line text-like `<input>`, `size` characters wide.
    Text { size: u32 },
    /// A `<textarea>` of `cols` characters by `rows` lines.
    TextArea { cols: u32, rows: u32 },
    /// A `<select>` as wide as its widest option and `rows` lines tall.
    Select { options: Vec<String>, rows: u32 },
    /// A `<button>` or button-type `<input>`: at least one line tall, and
    /// otherwise sized from its contents.
    Button,
}

/// The parsed value of a positive integer attribute, or `default`.
fn positive(value: Option<&str>, default: u32) -> u32 {
    value
        .and_then(|value| {
            // HTML's rules for parsing non-negative integers: leading
            // ASCII digits after whitespace; anything after them is ignored.
            let value = value.trim_start_matches(|c: char| c.is_ascii_whitespace());
            let end = value
                .find(|c: char| !c.is_ascii_digit())
                .unwrap_or(value.len());
            value[..end].parse::<u32>().ok()
        })
        .filter(|&value| value > 0)
        .unwrap_or(default)
}

impl FormControl {
    /// The control generated by element `node`, or `None` when it is not a
    /// form control with a default size.
    pub(crate) fn for_element(
        document: &HTMLDocument,
        node: NodeID,
        element: &html::ElementData,
    ) -> Option<Self> {
        if *element.get_namespace() != html::Namespace::Html {
            return None;
        }
        let attribute = |name: &str| {
            element
                .get_attributes()
                .iter()
                .find(|attribute| attribute.get_name() == name)
                .map(|attribute| attribute.get_value().as_str())
        };
        match element.get_name().as_str() {
            "input" => {
                let kind = attribute("type")
                    .map(|kind| kind.trim().to_ascii_lowercase())
                    .unwrap_or_default();
                match kind.as_str() {
                    "submit" | "reset" | "button" => Some(Self::Button),
                    "hidden" | "checkbox" | "radio" | "image" | "range" | "color" | "file" => None,
                    // Text, search, email, url, tel, password, number, and
                    // missing or unknown types are text fields.
                    _ => Some(Self::Text {
                        size: positive(attribute("size"), 20),
                    }),
                }
            }
            "textarea" => Some(Self::TextArea {
                cols: positive(attribute("cols"), 20),
                rows: positive(attribute("rows"), 2),
            }),
            "select" => {
                let size = positive(attribute("size"), 0);
                let rows = match (size, attribute("multiple").is_some()) {
                    (0, true) => 4,
                    (0, false) => 1,
                    (size, _) => size,
                };
                let mut options = Vec::new();
                collect_options(document, node, &mut options);
                Some(Self::Select { options, rows })
            }
            "button" => Some(Self::Button),
            _ => None,
        }
    }
}

/// Appends the text of every `<option>` below `node` (including those in
/// `<optgroup>`s) to `options`.
fn collect_options(document: &HTMLDocument, node: NodeID, options: &mut Vec<String>) {
    let Some(dom_node) = document.get_node(node) else {
        return;
    };
    for &child in dom_node.get_children() {
        let Some(child_node) = document.get_node(child) else {
            continue;
        };
        if let NodeKind::Element(element) = child_node.get_kind() {
            if element.get_name() == "option" {
                let mut text = String::new();
                collect_text(document, child, &mut text);
                options.push(text.split_whitespace().collect::<Vec<_>>().join(" "));
            } else {
                collect_options(document, child, options);
            }
        }
    }
}

fn collect_text(document: &HTMLDocument, node: NodeID, text: &mut String) {
    let Some(dom_node) = document.get_node(node) else {
        return;
    };
    for &child in dom_node.get_children() {
        match document.get_node(child).map(|child| child.get_kind()) {
            Some(NodeKind::Text(value)) => text.push_str(value),
            Some(NodeKind::Element(_)) => collect_text(document, child, text),
            _ => {}
        }
    }
}

/// A control's used content size where its `width` or `height` is `auto`.
#[derive(Debug, Clone, Copy, Default, PartialEq)]
pub(crate) struct ControlSize {
    /// The used content width, when `width` is `auto` and the control has a
    /// natural width.
    pub width: Option<f32>,
    /// The used content height, when `height` is `auto` and the control has
    /// a natural height.
    pub height: Option<f32>,
    /// A smallest content height for controls (buttons) whose height
    /// otherwise comes from their contents.
    pub min_height: f32,
}

impl Context<'_> {
    /// The natural content size of `block`'s form control, clamped by
    /// `min-*` / `max-*`, for each dimension whose property is `auto`.
    ///
    /// `cb_width` and `cb_height` are the containing block's size, `None`
    /// when indefinite.
    pub(crate) fn control_size(
        &self,
        block: &BlockBox,
        cb_width: Option<f32>,
        cb_height: Option<f32>,
    ) -> ControlSize {
        let Some(control) = &block.control else {
            return ControlSize::default();
        };
        let style = &block.style;
        let fonts = self.fonts;
        let character = fonts.font_advance(style.font, '0', style.font_size);
        let metrics = fonts.font_vertical_metrics(style.font, style.font_size);
        let line = metrics.ascent + metrics.descent + metrics.line_gap;
        let (width, height) = match control {
            FormControl::Text { size } => (Some(*size as f32 * character), Some(line)),
            FormControl::TextArea { cols, rows } => {
                (Some(*cols as f32 * character), Some(*rows as f32 * line))
            }
            FormControl::Select { options, rows } => {
                let widest = options
                    .iter()
                    .map(|option| fonts.font_text_width(style.font, option, style.font_size))
                    .fold(0.0_f32, f32::max);
                (Some(widest + SELECT_ARROW_ROOM), Some(*rows as f32 * line))
            }
            FormControl::Button => (None, None),
        };
        let clamp = |value: f32, min: Option<f32>, max: Option<f32>| {
            value
                .min(max.unwrap_or(f32::INFINITY))
                .max(min.unwrap_or(0.0))
        };
        let width = (style.width == Dimension::Auto)
            .then_some(width)
            .flatten()
            .map(|width| {
                clamp(
                    width,
                    style.content_width_for(style.min_width, cb_width),
                    style.content_width_for(style.max_width, cb_width),
                )
            });
        let height = (style.height == Dimension::Auto)
            .then_some(height)
            .flatten()
            .map(|height| {
                clamp(
                    height,
                    style.content_height_for(style.min_height, cb_width, cb_height),
                    style.content_height_for(style.max_height, cb_width, cb_height),
                )
            });
        ControlSize {
            width,
            height,
            min_height: if matches!(control, FormControl::Button) {
                line
            } else {
                0.0
            },
        }
    }
}
