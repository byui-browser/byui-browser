//! Default sizes of form controls (HTML §15.5).
//!
//! `<input>`, `<textarea>`, `<select>` and `<button>` stay ordinary block
//! containers so they can hold text, but when the author leaves `width` or
//! `height` as `auto` they take a natural content size measured from the
//! control's own font, the way browsers size them.
//!
//! Checkbox and radio inputs are different: layout sizes them like
//! replaced elements ([`CHECKBOX_RADIO_SIZE`]) and the painter draws them
//! itself from a [`ToggleControl`] on the box.
//!
//! Partial support: the sizes ignore scrollbars (`<textarea>`), list-box
//! `<select>` elements are sized like drop-downs but `size` lines tall and
//! still lay out their options as stacked blocks (no selection highlight or
//! bold group labels), and
//! checkbox, radio, `image`, `range`, `color` and `file` inputs get no
//! natural size.

use html::{HTMLDocument, NodeID, NodeKind};

use crate::box_tree::BlockBox;
use crate::layout::Context;
use crate::style::Dimension;
use crate::tree::{LineBox, LineFragment};

/// Room reserved beside a `<select>`'s widest option for its drop-down
/// arrow, in CSS pixels.
pub(crate) const SELECT_ARROW_ROOM: f32 = 20.0;

/// A form control whose `auto` size comes from its font.
#[derive(Debug, Clone, PartialEq)]
pub(crate) enum FormControl {
    /// A single-line text-like `<input>`, `size` characters wide.
    Text { size: u32 },
    /// A `<textarea>` of `cols` characters by `rows` lines.
    TextArea { cols: u32, rows: u32 },
    /// A `<select>` as wide as its widest option and `rows` lines tall.
    Select {
        /// The text of every option, in tree order.
        options: Vec<String>,
        /// How many lines tall the control is.
        rows: u32,
        /// For a single-choice drop-down (no `multiple`, `size` ≤ 1), the
        /// text it shows; `None` for a list box. A drop-down without options
        /// shows an empty string.
        drop_down: Option<String>,
    },
    /// A `<button>` or button-type `<input>`: at least one line tall, and
    /// otherwise sized from its contents.
    Button,
}

impl BlockBox {
    /// Whether the box is a single-choice `<select>` drop-down.
    pub(crate) fn is_drop_down(&self) -> bool {
        matches!(
            self.control,
            Some(FormControl::Select {
                drop_down: Some(_),
                ..
            })
        )
    }
}

/// The parsed value of a positive integer attribute, or `default`.
fn positive(value: Option<&str>, default: u32) -> u32 {
    value
        .and_then(|value| {
            // HTML's rules for parsing non-negative integers: leading
            // ASCII digits after whitespace; anything after them is ignored.
            let value = value.trim_start_matches(|c: char| c.is_ascii_whitespace());
            let end = value
                .find(|c: char| !c.is_ascii_digit())
                .unwrap_or(value.len());
            value[..end].parse::<u32>().ok()
        })
        .filter(|&value| value > 0)
        .unwrap_or(default)
}

impl FormControl {
    /// The control generated by element `node`, or `None` when it is not a
    /// form control with a default size.
    pub(crate) fn for_element(
        document: &HTMLDocument,
        node: NodeID,
        element: &html::ElementData,
    ) -> Option<Self> {
        if *element.get_namespace() != html::Namespace::Html {
            return None;
        }
        let attribute = |name: &str| {
            element
                .get_attributes()
                .iter()
                .find(|attribute| attribute.get_name() == name)
                .map(|attribute| attribute.get_value().as_str())
        };
        match element.get_name().as_str() {
            "input" => {
                let kind = attribute("type")
                    .map(|kind| kind.trim().to_ascii_lowercase())
                    .unwrap_or_default();
                match kind.as_str() {
                    "submit" | "reset" | "button" => Some(Self::Button),
                    "hidden" | "checkbox" | "radio" | "image" | "range" | "color" | "file" => None,
                    // Text, search, email, url, tel, password, number, and
                    // missing or unknown types are text fields.
                    _ => Some(Self::Text {
                        size: positive(attribute("size"), 20),
                    }),
                }
            }
            "textarea" => Some(Self::TextArea {
                cols: positive(attribute("cols"), 20),
                rows: positive(attribute("rows"), 2),
            }),
            "select" => {
                let size = positive(attribute("size"), 0);
                let rows = match (size, attribute("multiple").is_some()) {
                    (0, true) => 4,
                    (0, false) => 1,
                    (size, _) => size,
                };
                let mut entries = Vec::new();
                collect_options(document, node, false, &mut entries);
                let drop_down = (size <= 1 && attribute("multiple").is_none()).then(|| {
                    selected_entry(&entries)
                        .map(|entry| entry.text.clone())
                        .unwrap_or_default()
                });
                let options = entries.into_iter().map(|entry| entry.text).collect();
                Some(Self::Select {
                    options,
                    rows,
                    drop_down,
                })
            }
            "button" => Some(Self::Button),
            _ => None,
        }
    }
}

/// One `<option>` of a `<select>`.
struct OptionEntry {
    /// The option's text with white space collapsed.
    text: String,
    /// Whether it has the `selected` attribute.
    selected: bool,
    /// Whether it or its `<optgroup>` has the `disabled` attribute.
    disabled: bool,
}

/// The option a drop-down shows (HTML §4.10.7 selectedness): the last one
/// marked `selected`, or else the first one that isn't disabled.
fn selected_entry(entries: &[OptionEntry]) -> Option<&OptionEntry> {
    entries
        .iter()
        .rev()
        .find(|entry| entry.selected)
        .or_else(|| entries.iter().find(|entry| !entry.disabled))
}

/// Appends every `<option>` below `node` (including those in `<optgroup>`s)
/// to `options`. `disabled` is whether an enclosing group is disabled.
fn collect_options(
    document: &HTMLDocument,
    node: NodeID,
    disabled: bool,
    options: &mut Vec<OptionEntry>,
) {
    let Some(dom_node) = document.node(node) else {
        return;
    };
    for &child in dom_node.get_children() {
        let Some(child_node) = document.node(child) else {
            continue;
        };
        if let NodeKind::Element(element) = child_node.get_kind() {
            let has = |name: &str| {
                element
                    .get_attributes()
                    .iter()
                    .any(|attribute| attribute.get_name() == name)
            };
            let disabled = disabled || has("disabled");
            if element.get_name() == "option" {
                let mut text = String::new();
                collect_text(document, child, &mut text);
                options.push(OptionEntry {
                    text: text.split_whitespace().collect::<Vec<_>>().join(" "),
                    selected: has("selected"),
                    disabled,
                });
            } else {
                collect_options(document, child, disabled, options);
            }
        }
    }
}

fn collect_text(document: &HTMLDocument, node: NodeID, text: &mut String) {
    let Some(dom_node) = document.node(node) else {
        return;
    };
    for &child in dom_node.get_children() {
        match document.node(child).map(|child| child.get_kind()) {
            Some(NodeKind::Text(value)) => text.push_str(value),
            Some(NodeKind::Element(_)) => collect_text(document, child, text),
            _ => {}
        }
    }
}

/// A control's used content size where its `width` or `height` is `auto`.
#[derive(Debug, Clone, Copy, Default, PartialEq)]
pub(crate) struct ControlSize {
    /// The used content width, when `width` is `auto` and the control has a
    /// natural width.
    pub width: Option<f32>,
    /// The used content height, when `height` is `auto` and the control has
    /// a natural height.
    pub height: Option<f32>,
    /// A smallest content height for controls (buttons) whose height
    /// otherwise comes from their contents.
    pub min_height: f32,
}

impl Context<'_> {
    /// Clips a drop-down's lines (laid out from x = 0 in its content box)
    /// to `text_width`, dropping the characters that would run under the
    /// arrow, and makes each line box `line_width` wide.
    ///
    /// Partial support: text is cut at whole characters rather than clipped
    /// mid-glyph, since painting has no clip regions yet.
    pub(crate) fn clip_lines(&self, lines: &mut [LineBox], text_width: f32, line_width: f32) {
        for line in lines {
            line.rect.width = line_width;
            line.fragments.retain_mut(|fragment| match fragment {
                LineFragment::Text(text) => {
                    let room = text_width - text.rect.x;
                    if text.rect.width <= room {
                        return true;
                    }
                    let mut width = 0.0;
                    let mut end = 0;
                    for (index, character) in text.text.char_indices() {
                        let advance = self
                            .fonts
                            .font_advance(text.font, character, text.font_size);
                        if width + advance > room {
                            break;
                        }
                        width += advance;
                        end = index + character.len_utf8();
                    }
                    text.text.truncate(end);
                    text.rect.width = width;
                    end > 0
                }
                LineFragment::InlineBox(inline) => inline.rect.x < text_width,
                LineFragment::Atomic(atomic) => atomic.rect.x < text_width,
            });
        }
    }

    /// The natural content size of `block`'s form control, clamped by
    /// `min-*` / `max-*`, for each dimension whose property is `auto`.
    ///
    /// `cb_width` and `cb_height` are the containing block's size, `None`
    /// when indefinite.
    pub(crate) fn control_size(
        &self,
        block: &BlockBox,
        cb_width: Option<f32>,
        cb_height: Option<f32>,
    ) -> ControlSize {
        let Some(control) = &block.control else {
            return ControlSize::default();
        };
        let style = &block.style;
        let fonts = self.fonts;
        let character = fonts.font_advance(style.font, '0', style.font_size);
        let metrics = fonts.font_vertical_metrics(style.font, style.font_size);
        let line = metrics.ascent + metrics.descent + metrics.line_gap;
        let (width, height) = match control {
            FormControl::Text { size } => (Some(*size as f32 * character), Some(line)),
            FormControl::TextArea { cols, rows } => {
                (Some(*cols as f32 * character), Some(*rows as f32 * line))
            }
            FormControl::Select { options, rows, .. } => {
                let widest = options
                    .iter()
                    .map(|option| fonts.font_text_width(style.font, option, style.font_size))
                    .fold(0.0_f32, f32::max);
                (Some(widest + SELECT_ARROW_ROOM), Some(*rows as f32 * line))
            }
            FormControl::Button => (None, None),
        };
        let clamp = |value: f32, min: Option<f32>, max: Option<f32>| {
            value
                .min(max.unwrap_or(f32::INFINITY))
                .max(min.unwrap_or(0.0))
        };
        let width = (style.width == Dimension::Auto)
            .then_some(width)
            .flatten()
            .map(|width| {
                clamp(
                    width,
                    style.content_width_for(style.min_width, cb_width),
                    style.content_width_for(style.max_width, cb_width),
                )
            });
        let height = (style.height == Dimension::Auto)
            .then_some(height)
            .flatten()
            .map(|height| {
                clamp(
                    height,
                    style.content_height_for(style.min_height, cb_width, cb_height),
                    style.content_height_for(style.max_height, cb_width, cb_height),
                )
            });
        ControlSize {
            width,
            height,
            min_height: if matches!(control, FormControl::Button) {
                line
            } else {
                0.0
            },
        }
    }
}

/// The natural width and height of checkbox and radio controls, in CSS
/// pixels (Chrome's default). Author `width` / `height` override it.
pub const CHECKBOX_RADIO_SIZE: f32 = 13.0;

/// Which control a [`ToggleControl`] is.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum ControlKind {
    /// `<input type=checkbox>`: a rounded square.
    Checkbox,
    /// `<input type=radio>`: a circle.
    Radio,
}

/// A form control drawn by the painter in its box's content box, stored on
/// [`crate::LayoutBox::control`].
///
/// Partial support: `checked` and `disabled` reflect only the element's HTML
/// attributes as parsed. Clicking does not toggle checkedness yet (that needs
/// a checkedness state owned by the DOM / JS side), and `indeterminate` is
/// not supported.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub struct ToggleControl {
    /// Checkbox or radio button.
    pub kind: ControlKind,
    /// Whether the element has the `checked` attribute.
    pub checked: bool,
    /// Whether the element has the `disabled` attribute.
    pub disabled: bool,
}
