//! Renders tiny probe documents through the engine's real style, layout, and
//! paint stages, so CSS and HTML support is measured rather than assumed.

use std::panic::{AssertUnwindSafe, catch_unwind};

use layout::{FontMetrics, LayoutBox, LineFragment, Rect, Size, VerticalMetrics};
use paint::{DisplayItem, DisplayList};

/// Probe viewport in CSS pixels. Viewport-unit probes depend on it.
pub(crate) const VIEWPORT: Size = Size {
    width: 800.0,
    height: 600.0,
};

/// The shared probe document. Every element has an `id` so probes can target
/// it, and the base stylesheet gives each one a distinct background so that
/// any change in geometry shows up in the display list.
pub(crate) const FIXTURE_HTML: &str = "<!DOCTYPE html><html><head></head><body>\
<div id=\"w\"><div id=\"p\">\
<div id=\"t\">Probe words that wrap <span id=\"s\">inline span</span>\
<div id=\"c\" class=\"x y\" lang=\"en-US\">child one</div><div id=\"d\">child two</div></div>\
<div id=\"n\">next <em id=\"o\">em</em> text</div>\
<div id=\"m\"><a id=\"a\" href=\"#x\">link</a></div>\
<div id=\"e\"></div>\
</div></div></body></html>";

/// Backgrounds that make every fixture box visible in the display list.
pub(crate) const FIXTURE_CSS: &str = "#w{background-color:#010101}#p{background-color:#020202}\
#t{background-color:#030303}#s{background-color:#040404}#c{background-color:#050505}\
#d{background-color:#060606}#n{background-color:#070707}#m{background-color:#080808}\
#e{background-color:#090909}#o{background-color:#0a0a0a}#a{background-color:#0b0b0b}";

/// Deterministic font metrics: every glyph is half an em wide.
struct ProbeMetrics;

impl FontMetrics for ProbeMetrics {
    fn advance(&self, _character: char, font_size: f32) -> f32 {
        font_size * 0.5
    }

    fn vertical_metrics(&self, font_size: f32) -> VerticalMetrics {
        VerticalMetrics {
            ascent: font_size * 0.8,
            descent: font_size * 0.2,
            line_gap: 0.0,
        }
    }
}

/// The result of rendering one probe document.
pub(crate) struct Rendered {
    document: html::HTMLDocument,
    root: LayoutBox,
    /// What the engine would paint.
    pub list: DisplayList,
}

impl Rendered {
    /// The union of every fragment generated by the element with `id`, or
    /// `None` when the element generated no box at all.
    pub fn rect(&self, id: &str) -> Option<Rect> {
        let node = self.document.get_element_by_id(id)?;
        let mut found = None;
        collect_rects(&self.root, node, &mut found);
        found
    }

    /// The color of the background painted exactly over the element with
    /// `id`, or `None` when nothing is painted there.
    pub fn fill_color(&self, id: &str) -> Option<paint::Color> {
        let rect = self.rect(id)?;
        self.list.items.iter().rev().find_map(|item| match item {
            DisplayItem::FillRect {
                rect: painted,
                color,
            }
            | DisplayItem::FillRoundedRect {
                rect: painted,
                color,
                ..
            } if *painted == rect => Some(*color),
            _ => None,
        })
    }

    /// The `(x, baseline)` of the first painted text run containing `needle`.
    pub fn text_position(&self, needle: &str) -> Option<(f32, f32)> {
        self.list.items.iter().find_map(|item| match item {
            DisplayItem::Text {
                text, x, baseline, ..
            } if text.contains(needle) => Some((*x, *baseline)),
            _ => None,
        })
    }

    /// Whether any painted text run contains `needle`.
    pub fn paints_text(&self, needle: &str) -> bool {
        self.list
            .items
            .iter()
            .any(|item| matches!(item, DisplayItem::Text { text, .. } if text.contains(needle)))
    }
}

fn union(a: Rect, b: Rect) -> Rect {
    let x = a.x.min(b.x);
    let y = a.y.min(b.y);
    Rect {
        x,
        y,
        width: (a.x + a.width).max(b.x + b.width) - x,
        height: (a.y + a.height).max(b.y + b.height) - y,
    }
}

fn add_rect(found: &mut Option<Rect>, rect: Rect) {
    *found = Some(found.map_or(rect, |prior| union(prior, rect)));
}

fn collect_rects(layout_box: &LayoutBox, node: html::NodeID, found: &mut Option<Rect>) {
    if layout_box.node == Some(node) {
        add_rect(found, layout_box.rect);
    }
    for line in &layout_box.lines {
        for fragment in &line.fragments {
            match fragment {
                LineFragment::InlineBox(inline) if inline.node == node => {
                    add_rect(found, inline.rect)
                }
                LineFragment::Atomic(atomic) => collect_rects(atomic, node, found),
                _ => {}
            }
        }
    }
    for child in &layout_box.children {
        collect_rects(child, node, found);
    }
}

/// Styles, lays out, and paints `html` with `css` as its only author
/// stylesheet. Returns `None` if any engine stage panics, which the audit
/// treats as "does not work".
pub(crate) fn render(html: &str, css: &str) -> Option<Rendered> {
    catch_unwind(AssertUnwindSafe(|| {
        let document = html::parse_raw_html(html.to_owned());
        let sheet = css::parse_stylesheet(css);
        let styles = css::style_document(&document, &[sheet]);
        let tree = layout::layout_document(&document, &styles, VIEWPORT, &ProbeMetrics);
        let list = paint::paint_document(&tree);
        Rendered {
            document,
            root: tree.root,
            list,
        }
    }))
    .ok()
}

/// Renders the shared fixture with `extra` appended to its base stylesheet.
pub(crate) fn render_fixture(extra: &str) -> Option<Rendered> {
    render(FIXTURE_HTML, &format!("{FIXTURE_CSS}{extra}"))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn fixture_boxes_are_visible_and_addressable() {
        let base = render_fixture("").unwrap();
        for id in ["w", "p", "t", "c", "d", "n", "s"] {
            assert!(base.rect(id).is_some(), "#{id} should generate a box");
        }
        assert!(base.paints_text("child one"));
        // Supported declarations change the display list; base is stable.
        let again = render_fixture("").unwrap();
        assert_eq!(base.list, again.list);
        let sized = render_fixture("#t{height:300px}").unwrap();
        assert_ne!(base.list, sized.list);
        assert_eq!(sized.rect("t").unwrap().height, 300.0);
    }
}
